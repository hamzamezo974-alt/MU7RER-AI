/** تخريج الآية القرآنية وعزوها لسورتها ورقمها */
export function takhrijAyahNative(text: string): { formattedText: string; citationNote: string } {
  const norm = normalizeArabic(text);
  for (const item of QURAN_CORPUS) {
    if (item.keys.some((k) => norm.includes(normalizeArabic(k)) || normalizeArabic(k).includes(norm))) {
      return {
        formattedText: `﴿${item.uthmani}﴾`,
        citationNote: `تخريج: [سورة ${item.surah}: الآية ${item.ayah}].`,
      };
    }
  }
  const clean = text.replace(/^[«"﴿(\[]+|[»"﴾)\]]+$/g, "").trim();
  return {
    formattedText: `﴿${clean}﴾`,
    citationNote: `تخريج: آية كريمة — يُراجع موضعها في المعجم المفهرس لألفاظ القرآن الكريم: «${stripDiacritics(clean).slice(0, 45)}».`,
  };
}

/** تخريج الحديث النبوي أو الأثر وعزوه لمصادره ودرجته */
export function takhrijHadithNative(text: string): { formattedText: string; citationNote: string } {
  const norm = normalizeArabic(text);
  for (const item of HADITH_CORPUS) {
    if (item.keys.some((k) => norm.includes(normalizeArabic(k)) || normalizeArabic(k).includes(norm))) {
      return {
        formattedText: `«${item.matn}»`,
        citationNote: `تخريج: ${item.source}. حكمه: (${item.grade}).`,
      };
    }
  }
  const clean = text.replace(/^[«"(\[]+|[»")\]]+$/g, "").trim();
  return {
    formattedText: `«${clean}»`,
    citationNote: `تخريج: حديث/أثر («${stripDiacritics(clean).slice(0, 50)}…») — يُستخرج إسناده ومتنه من «تحفة الأشراف» للمزي و«المعجم المفهرس لألفاظ الحديث النبوي».`,
  };
}

/** ترجمة العَلَم واستخراج كشاف الأعلام والبلدان والمصادر من النص */
export function translateAndIndexNamesNative(text: string): string {
  const norm = normalizeArabic(text);

  // إذا كان التحديد علماً مفرداً أو قصيراً، أخرج ترجمته الوافية
  for (const entry of SCHOLARS_BIO) {
    if (entry.keys.some((k) => norm.includes(normalizeArabic(k)))) {
      const b = entry.bio;
      return `ترجمة عَلَم: ${b.name} (${b.title}، ت ${b.deathYear}، ${b.school}). ${b.summary}`;
    }
  }

  // استخراج الفهارس العلمية الشاملة من النص المحدد
  const foundAyahs: string[] = [];
  const foundHadiths: string[] = [];
  const foundNames: string[] = [];
  const foundPlaces: string[] = [];
  const foundBooks: string[] = [];

  for (const q of QURAN_CORPUS) {
    if (q.keys.some((k) => norm.includes(normalizeArabic(k)))) {
      foundAyahs.push(`﴿${q.uthmani}﴾ [${q.surah}: ${q.ayah}]`);
    }
  }
  for (const h of HADITH_CORPUS) {
    if (h.keys.some((k) => norm.includes(normalizeArabic(k)))) {
      foundHadiths.push(`«${h.matn}» (${h.grade})`);
    }
  }
  for (const s of SCHOLARS_BIO) {
    if (s.keys.some((k) => norm.includes(normalizeArabic(k)))) {
      foundNames.push(`${s.bio.name} (ت ${s.bio.deathYear})`);
    }
  }

  // صيد الكنى والأنساب (أبو ...، ابن ...، ... بن ...)
  const nameRegex = /(?:أبو|أبي|أبا|ابن|بن|الإمام|الحافظ|الشيخ)\s+[\u0621-\u064A]+(?:\s+بن\s+[\u0621-\u064A]+)?/g;
  const regexNames = text.match(nameRegex) ?? [];
  for (const n of regexNames) {
    if (!foundNames.some((fn) => fn.includes(n.trim()))) foundNames.push(n.trim());
  }

  const PLACES = ["مكة", "المدينة", "بغداد", "دمشق", "البصرة", "الكوفة", "مصر", "القاهرة", "نيسابور", "قرطبة", "إشبيلية", "فاس", "القيروان", "بخارى", "سمرقند", "القدس", "بيت المقدس", "اليمن", "الشام", "العراق", "خراسان", "الأندلس", "الحجاز"];
  for (const p of PLACES) {
    if (norm.includes(normalizeArabic(p))) foundPlaces.push(p);
  }

  const BOOKS = ["الكتاب", "الموطأ", "الرسالة", "الأم", "المسند", "الصحيح", "الجامع", "السنن", "فتح الباري", "المجموع", "المقدمة", "الإتقان", "العين", "لسان العرب", "القاموس", "تهذيب", "الطبقات", "التاريخ"];
  for (const b of BOOKS) {
    if (text.includes(`«${b}»`) || text.includes(`كتاب ${b}`)) foundBooks.push(b);
  }

  if (text.trim().split(/\s+/).length <= 5 && foundNames.length > 0) {
    return `ترجمة عَلَم: ${foundNames[0]} — عَلَمٌ مذكور في المتن، يُراجع في «سير أعلام النبلاء» للذهبي و«الوافي بالوفيات» للصفدي.`;
  }

  return [
    `فهرس الآيات: ${foundAyahs.length ? foundAyahs.join(" ؛ ") : "لا يوجد"}`,
    `فهرس الأحاديث: ${foundHadiths.length ? foundHadiths.join(" ؛ ") : "لا يوجد"}`,
    `فهرس الأعلام: ${foundNames.length ? [...new Set(foundNames)].join(" ، ") : "لا يوجد"}`,
    `فهرس الأماكن: ${foundPlaces.length ? [...new Set(foundPlaces)].join(" ، ") : "لا يوجد"}`,
    `فهرس المصادر: ${foundBooks.length ? [...new Set(foundBooks)].join(" ، ") : "لا يوجد"}`,
  ].join("\n");
}
